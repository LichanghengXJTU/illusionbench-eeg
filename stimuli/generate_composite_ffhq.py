"""stimuli/generate_composite_ffhq.py — composite-face battery from FFHQ identities.

Reuses the FFHQ identities + landmarks generated by `generate_thatcher_ffhq.py`
(at data/stimuli_ffhq/identities/, identity_landmarks/, identity_manifest.csv).

For each base identity i, sample a paired identity j (different from i; gender
match not enforced here for simplicity since FFHQ doesn't ship gender labels in
the gaunernst webdataset). Cut each image horizontally at the nose-tip y
(MediaPipe landmark 1, the nose-tip) and compose:

  V1 aligned_same       = top(i) + bottom(i), no horizontal shift   (== original i)
  V2 aligned_diff       = top(i) + bottom(j), no shift
  V3 misaligned_same    = top(i) + bottom(i), bottom shifted right 40 px (relative to native 1024)
  V4 misaligned_diff    = top(i) + bottom(j), bottom shifted right 40 px

We keep the same V1/V2/V3/V4 naming convention as Thatcher so downstream
extract_embeddings + compute_metrics scripts work unchanged.

Composite-face Sensitivity Index (CSI_pert):
  CSI_pert = mean_i d(V1_i, V2_i) / mean_i d(V3_i, V4_i)

  Higher in aligned ⇒ holistic binding makes the embedding sensitive to bottom-identity
  change. Lower in misaligned ⇒ shifted bottom is read featurally, easier to ignore.
"""
from __future__ import annotations
import argparse
import csv
import json
from dataclasses import dataclass, asdict
from pathlib import Path

import cv2
import numpy as np
from PIL import Image
from tqdm import tqdm

import sys
sys.path.insert(0, str(Path(__file__).parent.parent))
from stimuli.generate_thatcher import paste_with_alpha


# MediaPipe FaceMesh nose tip indices (with refine_landmarks=True 478 points).
# Index 1 is the canonical nose tip. We'll also use 168 (between eyes) as a
# safety cross-check that the chosen y is roughly mid-face.
NOSE_TIP_IDX = 1
NOSE_BRIDGE_IDX = 168


def get_cut_y(lm_arr: np.ndarray, img_h: int) -> int:
    """Return horizontal cut row (in pixel coords) at nose-tip y."""
    y = float(lm_arr[NOSE_TIP_IDX, 1])
    return int(np.clip(round(y), 1, img_h - 1))


def make_top_bot(img_rgb: np.ndarray, cut_y: int):
    top = img_rgb[:cut_y].copy()
    bot = img_rgb[cut_y:].copy()
    return top, bot


def compose(top: np.ndarray, bot: np.ndarray,
            cut_y: int, shift_px: int, img_h: int, img_w: int,
            blur_sigma: float) -> np.ndarray:
    """Stack top (rows 0..cut_y) + bot (rows cut_y..H), with optional horizontal
    shift on the bottom (positive = right). Soft-blend the seam by a 5-px Gaussian
    on the alpha channel along the cut row."""
    canvas = np.zeros((img_h, img_w, 3), dtype=np.uint8)
    canvas[:cut_y] = top
    # Shift bottom horizontally: place bot into a canvas of same H starting at row cut_y
    bot_h, bot_w = bot.shape[:2]
    target = np.zeros((bot_h, img_w, 3), dtype=np.uint8)
    if shift_px == 0:
        target[:, :bot_w] = bot
    elif shift_px > 0:
        end = min(img_w, bot_w + shift_px)
        target[:, shift_px:end] = bot[:, :end - shift_px]
    else:
        s = -shift_px
        end = min(img_w, bot_w - s)
        target[:, :end] = bot[:, s:s + end]
    canvas[cut_y:cut_y + bot_h] = target
    # Soft-blend a 5px vertical strip across the cut to hide the seam
    if blur_sigma > 0:
        strip_half = max(2, int(blur_sigma * 2))
        y0 = max(0, cut_y - strip_half)
        y1 = min(img_h, cut_y + strip_half)
        if y1 > y0 + 1:
            patch = canvas[y0:y1].copy()
            blurred = cv2.GaussianBlur(patch, (0, 0), sigmaX=blur_sigma, sigmaY=blur_sigma)
            # only apply to a narrow band centered on the seam
            alpha = np.zeros((y1 - y0, 1, 1), dtype=np.float32)
            seam_offset = cut_y - y0
            for r in range(y1 - y0):
                d = abs(r - seam_offset)
                alpha[r, 0, 0] = max(0, 1 - d / strip_half)
            canvas[y0:y1] = (patch.astype(np.float32) * (1 - alpha)
                             + blurred.astype(np.float32) * alpha).astype(np.uint8)
    return canvas


@dataclass
class Identity:
    identity_id: int
    ffhq_name: str
    paired_with: int
    paired_ffhq_name: str
    canonical_png_path: str
    landmarks_json_path: str


def main(args):
    src_root = Path(args.src_root)
    src_identities = src_root / "identities"
    src_landmarks = src_root / "identity_landmarks"
    src_identity_manifest = src_root / "identity_manifest.csv"

    out_root = Path(args.output_root)
    stim_dir = out_root / "composite"
    identities_dir = out_root / "identities"
    landmarks_dir = out_root / "identity_landmarks"
    for d in (stim_dir, identities_dir, landmarks_dir):
        d.mkdir(parents=True, exist_ok=True)

    src_records = []
    with open(src_identity_manifest) as f:
        for row in csv.DictReader(f):
            src_records.append(row)
    print(f"[init] {len(src_records)} source identities")

    rng = np.random.default_rng(args.seed)

    # Build pairs: each base identity gets a different identity as its bottom donor.
    # Easiest: shuffle indices; pair i with shuffled[i] (skip self-pairs via shift).
    n = len(src_records)
    pair_idx = (np.arange(n) + 1 + rng.integers(1, n - 1)) % n  # deterministic non-self
    # ensure no self-pair
    for i in range(n):
        if pair_idx[i] == i:
            pair_idx[i] = (i + 1) % n

    manifest_rows = []
    identity_records = []
    blur_sigma = args.blur_sigma
    target_n = args.target_n if args.target_n > 0 else n

    pbar = tqdm(range(min(n, target_n)), desc="composite")
    for k in pbar:
        i = k
        j = int(pair_idx[i])
        rec_i = src_records[i]
        rec_j = src_records[j]
        identity_id = int(rec_i["identity_id"])
        paired_id = int(rec_j["identity_id"])

        png_i = Path(rec_i["canonical_png_path"])
        png_j = Path(rec_j["canonical_png_path"])
        lm_i = Path(rec_i["landmarks_json_path"])
        if not (png_i.exists() and png_j.exists() and lm_i.exists()):
            continue
        bgr_i = cv2.imread(str(png_i)); rgb_i = cv2.cvtColor(bgr_i, cv2.COLOR_BGR2RGB)
        bgr_j = cv2.imread(str(png_j)); rgb_j = cv2.cvtColor(bgr_j, cv2.COLOR_BGR2RGB)
        h, w = rgb_i.shape[:2]
        if rgb_j.shape[:2] != (h, w):
            rgb_j = cv2.resize(rgb_j, (w, h), interpolation=cv2.INTER_CUBIC)

        with open(lm_i) as f:
            lm_data = json.load(f)
        lm_arr = np.array(lm_data["landmarks"], dtype=np.float32)
        cut_y = get_cut_y(lm_arr, h)

        top_i, bot_i = make_top_bot(rgb_i, cut_y)
        top_i_j, bot_j = make_top_bot(rgb_j, cut_y)  # bot_j is the donor bottom
        shift = args.misalign_shift_px

        v1 = compose(top_i, bot_i, cut_y, 0,     h, w, blur_sigma)  # aligned_same  (==rgb_i)
        v2 = compose(top_i, bot_j, cut_y, 0,     h, w, blur_sigma)  # aligned_diff
        v3 = compose(top_i, bot_i, cut_y, shift, h, w, blur_sigma)  # misaligned_same
        v4 = compose(top_i, bot_j, cut_y, shift, h, w, blur_sigma)  # misaligned_diff

        # symlink original identity into output for downstream tools
        ident_sym = identities_dir / f"identity_{identity_id:04d}.png"
        lm_sym = landmarks_dir / f"identity_{identity_id:04d}.json"
        if not ident_sym.exists():
            try: ident_sym.symlink_to(png_i.resolve())
            except FileExistsError: pass
        if not lm_sym.exists():
            try: lm_sym.symlink_to(lm_i.resolve())
            except FileExistsError: pass

        identity_records.append(Identity(
            identity_id=identity_id,
            ffhq_name=rec_i.get("lfw_name", rec_i.get("ffhq_name", "")),
            paired_with=paired_id,
            paired_ffhq_name=rec_j.get("lfw_name", rec_j.get("ffhq_name", "")),
            canonical_png_path=str(ident_sym),
            landmarks_json_path=str(lm_sym),
        ))

        # Note: condition naming reuses V1..V4 + same suffixes so existing
        # compute_metrics.py (which looks up by stim_id "thatcher_idXXXX_VK_*") works
        for vname, vimg in [
            ("V1_upright_normal",   v1),  # aligned_same
            ("V2_upright_thatched", v2),  # aligned_diff
            ("V3_inverted_normal",  v3),  # misaligned_same
            ("V4_inverted_thatched",v4),  # misaligned_diff
        ]:
            path = stim_dir / f"identity_{identity_id:04d}_{vname}.png"
            Image.fromarray(vimg).save(path)
            manifest_rows.append({
                "stim_id": f"thatcher_id{identity_id:04d}_{vname}",
                "identity_id": identity_id,
                "lfw_name": rec_i.get("lfw_name", rec_i.get("ffhq_name", "")),
                "paradigm": "composite",
                "condition": vname,
                "orientation": "aligned" if vname.startswith(("V1","V2")) else "misaligned",
                "thatcherized": int(vname.startswith(("V2","V4"))),
                "path": str(path),
            })

        pbar.set_postfix(accepted=len(identity_records))

    manifest_path = out_root / "thatcher_manifest.csv"  # reuse name for downstream compat
    with open(manifest_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(manifest_rows[0].keys()))
        writer.writeheader()
        writer.writerows(manifest_rows)
    identity_manifest_path = out_root / "identity_manifest.csv"
    with open(identity_manifest_path, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(asdict(identity_records[0]).keys()))
        writer.writeheader()
        writer.writerows([asdict(r) for r in identity_records])

    print(f"[done] {len(identity_records)} composite identities, {len(manifest_rows)} stimuli")
    print(f"  identity manifest: {identity_manifest_path}")
    print(f"  stimulus manifest: {manifest_path}")


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--src_root", required=True)
    p.add_argument("--output_root", required=True)
    p.add_argument("--target_n", type=int, default=0, help="0 = use all source identities")
    p.add_argument("--misalign_shift_px", type=int, default=80)
    p.add_argument("--blur_sigma", type=float, default=5.0)
    p.add_argument("--seed", type=int, default=20260521)
    return p.parse_args()


if __name__ == "__main__":
    main(parse_args())
